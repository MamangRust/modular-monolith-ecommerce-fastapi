"""Category handler"""

from __future__ import annotations

from typing import Any, Protocol


class CategoryQueryHandlerPort(Protocol):
    async def FindAll(self, request: Any, context: Any) -> Any: ...

    async def FindById(self, request: Any, context: Any) -> Any: ...

    async def FindByActive(self, request: Any, context: Any) -> Any: ...

    async def FindByTrashed(self, request: Any, context: Any) -> Any: ...


class CategoryCommandHandlerPort(Protocol):
    async def Create(self, request: Any, context: Any) -> Any: ...

    async def Update(self, request: Any, context: Any) -> Any: ...

    async def TrashedCategory(self, request: Any, context: Any) -> Any: ...

    async def RestoreCategory(self, request: Any, context: Any) -> Any: ...

    async def DeleteCategoryPermanent(self, request: Any, context: Any) -> Any: ...

    async def RestoreAllCategory(self, request: Any, context: Any) -> Any: ...

    async def DeleteAllCategoryPermanent(self, request: Any, context: Any) -> Any: ...


class CategoryStatsHandlerPort(Protocol):
    async def FindMonthlyTotalPrices(self, request: Any, context: Any) -> Any: ...

    async def FindYearlyTotalPrices(self, request: Any, context: Any) -> Any: ...

    async def FindMonthPrice(self, request: Any, context: Any) -> Any: ...

    async def FindYearPrice(self, request: Any, context: Any) -> Any: ...


class CategoryStatsByIdHandlerPort(Protocol):
    async def FindMonthlyTotalPricesById(self, request: Any, context: Any) -> Any: ...

    async def FindYearlyTotalPricesById(self, request: Any, context: Any) -> Any: ...

    async def FindMonthPriceById(self, request: Any, context: Any) -> Any: ...

    async def FindYearPriceById(self, request: Any, context: Any) -> Any: ...


class CategoryStatsByMerchantHandlerPort(Protocol):
    async def FindMonthlyTotalPricesByMerchant(
        self, request: Any, context: Any
    ) -> Any: ...

    async def FindYearlyTotalPricesByMerchant(
        self, request: Any, context: Any
    ) -> Any: ...

    async def FindMonthPriceByMerchant(self, request: Any, context: Any) -> Any: ...

    async def FindYearPriceByMerchant(self, request: Any, context: Any) -> Any: ...


__all__ = [
    "CategoryCommandHandlerPort",
    "CategoryQueryHandlerPort",
    "CategoryStatsByIdHandlerPort",
    "CategoryStatsByMerchantHandlerPort",
    "CategoryStatsHandlerPort",
]
