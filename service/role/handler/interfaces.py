"""Role handler"""

from __future__ import annotations

from typing import Any, Protocol


class RoleQueryHandlerPort(Protocol):
    async def FindAllRole(self, request: Any, context: Any) -> Any: ...

    async def FindByIdRole(self, request: Any, context: Any) -> Any: ...

    async def FindByActive(self, request: Any, context: Any) -> Any: ...

    async def FindByTrashed(self, request: Any, context: Any) -> Any: ...

    async def FindByUserId(self, request: Any, context: Any) -> Any: ...


class RoleCommandHandlerPort(Protocol):
    async def CreateRole(self, request: Any, context: Any) -> Any: ...

    async def UpdateRole(self, request: Any, context: Any) -> Any: ...

    async def TrashedRole(self, request: Any, context: Any) -> Any: ...

    async def RestoreRole(self, request: Any, context: Any) -> Any: ...

    async def DeleteRolePermanent(self, request: Any, context: Any) -> Any: ...

    async def RestoreAllRole(self, request: Any, context: Any) -> Any: ...

    async def DeleteAllRolePermanent(self, request: Any, context: Any) -> Any: ...


__all__ = ["RoleCommandHandlerPort", "RoleQueryHandlerPort"]
