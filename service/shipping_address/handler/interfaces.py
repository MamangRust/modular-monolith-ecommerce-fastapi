"""Shipping address handler"""

from __future__ import annotations

from typing import Any, Protocol


class ShippingQueryHandlerPort(Protocol):
    async def FindAll(self, request: Any, context: Any) -> Any: ...

    async def FindById(self, request: Any, context: Any) -> Any: ...

    async def FindByOrder(self, request: Any, context: Any) -> Any: ...

    async def FindByActive(self, request: Any, context: Any) -> Any: ...

    async def FindByTrashed(self, request: Any, context: Any) -> Any: ...


class ShippingCommandHandlerPort(Protocol):
    async def CreateShipping(self, request: Any, context: Any) -> Any: ...

    async def UpdateShipping(self, request: Any, context: Any) -> Any: ...

    async def TrashedShipping(self, request: Any, context: Any) -> Any: ...

    async def RestoreShipping(self, request: Any, context: Any) -> Any: ...

    async def DeleteShippingPermanent(self, request: Any, context: Any) -> Any: ...

    async def RestoreAllShipping(self, request: Any, context: Any) -> Any: ...

    async def DeleteShippingByOrderPermanent(
        self, request: Any, context: Any
    ) -> Any: ...

    async def DeleteAllShippingPermanent(self, request: Any, context: Any) -> Any: ...


__all__ = ["ShippingCommandHandlerPort", "ShippingQueryHandlerPort"]
